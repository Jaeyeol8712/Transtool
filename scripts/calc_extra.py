def _tire_table():
    rows = []
    for code in ("0119", "2522", "4824", "1026"):
        wk, yy = int(code[:2]), 2000 + int(code[2:])
        monday = date.fromisocalendar(yy, wk, 1)
        rows.append([code, f"{yy}년 {wk}주차", f"{monday.month}월 {monday.day}일 무렵", f"약 {2026 - yy}년"])
    return _tbl(["DOT 4자리", "생산 시기", "그 주 월요일", "2026년 기준 경과"], rows)


def _fuel_table():
    rows = []
    for km, eff in ((100, 10), (100, 15), (400, 12), (400, 16)):
        liters = km / eff
        rows.append([f"{km}km", f"{eff}km/L", f"{liters:.1f}L", _won(liters * 1700)])
    return _tbl(["거리", "연비", "필요 연료", "리터당 1,700원 가정 시"], rows, (3,))


def _service_table():
    rows = []
    for a, b in ((date(2023, 3, 2), date(2026, 3, 1)), (date(2020, 1, 1), date(2026, 6, 30)), (date(2025, 11, 1), date(2026, 10, 31))):
        days = (b - a).days + 1
        rows.append([f"{a:%Y.%m.%d} ~ {b:%Y.%m.%d}", f"{days:,}일"])
    return _tbl(["입사일 ~ 퇴사일(마지막 근무일)", "총 재직일수(양 끝 포함)"], rows, (1,))


def _date_table():
    base = date(2026, 3, 1)
    rows = [[f"{n}일째", f"{base + timedelta(days=n - 1):%Y년 %m월 %d일}"] for n in (100, 200, 300, 365, 1000)]
    return _tbl(["시작일 2026-03-01을 1일로", "날짜"], rows)


