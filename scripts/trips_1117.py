def page(t, style):
    out = _page(t, style)
    ex = "".join(f'<h2 class="sec">{h}</h2>\n{b}\n' for h, b in t.get("extra", []))
    src = "".join(f'<li><a href="{html.escape(u)}" rel="nofollow noopener" target="_blank">{html.escape(n)}</a></li>' for n, u in t.get("sources", []))
    ex += f'<h2 class="sec">근거 자료 ({CHK})</h2>\n<ul>{src}</ul>\n'
    key = '<h2 class="sec">자주 묻는 질문</h2>'
    return out.replace(key, ex + key, 1)


